MERGE INTO ESTADO dst
USING (SELECT 1 AS ID_ESTADO, 'São Paulo' AS NM_ESTADO, 'SP' AS SG_ESTADO FROM DUAL) src
ON (dst.ID_ESTADO = src.ID_ESTADO)
WHEN NOT MATCHED THEN
  INSERT (ID_ESTADO, NM_ESTADO, SG_ESTADO) VALUES (src.ID_ESTADO, src.NM_ESTADO, src.SG_ESTADO);

