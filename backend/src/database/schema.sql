CREATE OR REPLACE VIEW "VW_INDICADORES_DOADOR" AS
SELECT d.CPF,
       d.NM_DOADOR,
       NVL(d.NR_DOACOES, 0) AS LOTES_DOADOS,
       NVL((SELECT SUM(doa.PESO_KG) FROM DOACAO doa WHERE TRIM(doa.CPF_INFORMADO) = TRIM(d.CPF)), NVL(d.NR_DOACOES, 0) * 1.5) AS KG_REAPROVEITADOS,
       NVL((SELECT COUNT(DISTINCT doa.CNPJ_EMPRESA) FROM DOACAO doa WHERE TRIM(doa.CPF_INFORMADO) = TRIM(d.CPF)), 1) AS EMPRESAS_APOIADAS,
       NVL((SELECT SUM(doa.PESO_KG) FROM DOACAO doa WHERE TRIM(doa.CPF_INFORMADO) = TRIM(d.CPF)), NVL(d.NR_DOACOES, 0) * 1.5) * 80 AS AGUA_POUPADA_LITROS
  FROM DOADOR d;

CREATE OR REPLACE VIEW "VW_INDICADORES_CONFECCIONISTA" AS
SELECT c.CPF_CNPJ,
       c.NM_CONFECCIONISTA,
       (SELECT COUNT(*) FROM PROJETOS p WHERE TRIM(p.CPF_CNPJ_CONFECCIONISTA) = TRIM(c.CPF_CNPJ)) AS TOTAL_PROJETOS
  FROM CONFECCIONISTA c;

CREATE OR REPLACE VIEW "VW_INDICADORES_EMPRESA" AS
SELECT e.CNPJ,
       e.NM_FANTASIA,
       (SELECT COUNT(*) FROM DOACAO d WHERE TRIM(d.CNPJ_EMPRESA) = TRIM(e.CNPJ)) AS TOTAL_DOACOES,
       (SELECT NVL(SUM(d.PESO_KG), 0) FROM DOACAO d WHERE TRIM(d.CNPJ_EMPRESA) = TRIM(e.CNPJ)) AS KG_DOACOES,
       (SELECT COUNT(*) FROM DESCONTO dc WHERE TRIM(dc.CNPJ_EMPRESA) = TRIM(e.CNPJ)) AS TOTAL_CUPONS
  FROM EMPRESA e;
